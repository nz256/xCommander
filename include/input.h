#ifndef INPUT_H
#define INPUT_H

#include <wchar.h>

typedef enum {
	ACT_NONE = 0, ACT_CHAR, ACT_ALT_CHAR, ACT_RESIZE,
	ACT_UP, ACT_DOWN, ACT_LEFT, ACT_RIGHT,
	ACT_HOME, ACT_END, ACT_PGUP, ACT_PGDN,
	ACT_CTRL_PGUP, ACT_CTRL_PGDN,
	ACT_SHIFT_UP, ACT_SHIFT_DOWN, ACT_SHIFT_LEFT, ACT_SHIFT_RIGHT,
	ACT_CTRL_LEFT, ACT_CTRL_RIGHT,
	ACT_WORD_SEL_LEFT, ACT_WORD_SEL_RIGHT,
	ACT_INSERT, ACT_SHIFT_INSERT, ACT_DELETE, ACT_BACKSPACE,
	ACT_TAB, ACT_ENTER,
	ACT_INSERT_NAME, ACT_INSERT_LEFT_PATH, ACT_INSERT_RIGHT_PATH,
	ACT_ESC,
	ACT_F1, ACT_F2, ACT_F3, ACT_F4, ACT_SHIFT_F4,
	ACT_F5, ACT_F6, ACT_F7, ACT_SHIFT_F7, ACT_F8, ACT_F9, ACT_F10,
	ACT_CTRL_A, ACT_CTRL_B, ACT_CTRL_C, ACT_CTRL_E, ACT_CTRL_F,
	ACT_CTRL_O, ACT_CTRL_Q, ACT_CTRL_U, ACT_CTRL_V, ACT_CTRL_X, ACT_CTRL_Y
} KeyAction;

typedef struct {
	KeyAction action;
	wchar_t ch;
} InputEvent;

void input_enable_raw(void);
void input_restore_sane(void);
InputEvent input_read(void);

#endif
